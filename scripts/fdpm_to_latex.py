class PdfBuildError(Exception):
    """Raised when the LaTeX engine fails to produce a PDF."""


def compile_pdf(
    tex_path: Path,
    *,
    engine: str,
    bib_path: Path | None,
    passes: int = 2,
    keep_aux: bool = False,
) -> Path:
    """Compile ``tex_path`` to a PDF in the same directory using ``engine``.

    The function runs the engine ``passes`` times to resolve cross-references
    (TOC, ``\\autoref``, ``\\cite``). When a separate ``.bib`` file is present
    the function does NOT invoke ``bibtex`` — the document uses
    ``thebibliography`` directly and the ``.bib`` is supplementary metadata.
    Auxiliary files (.aux, .log, .out, .toc, .lof, .lot) are removed unless
    ``keep_aux=True``.

    Returns the produced PDF path. Raises ``PdfBuildError`` on failure,
    including the tail of the engine log when available.
    """
    if shutil.which(engine) is None:
        raise PdfBuildError(
            f"{engine!r} not found on PATH. Install TeXLive / MiKTeX, or "
            f"choose a different --engine."
        )
    workdir = tex_path.parent
    base = tex_path.stem
    cmd = [
        engine,
        "-interaction=nonstopmode",
        "-halt-on-error",
        "-file-line-error",
        tex_path.name,
    ]
    last_log = ""
    for n in range(passes):
        proc = subprocess.run(
            cmd, cwd=workdir, capture_output=True, text=True, check=False
        )
        last_log = proc.stdout + proc.stderr
        if proc.returncode != 0:
            log_file = workdir / f"{base}.log"
            tail = ""
            if log_file.is_file():
                try:
                    tail_lines = log_file.read_text(
                        encoding="utf-8", errors="replace"
                    ).splitlines()[-40:]
                    tail = "\n".join(tail_lines)
                except OSError:
                    pass
            raise PdfBuildError(
                f"{engine} failed on pass {n + 1}/{passes} for {tex_path}.\n"
                f"--- log tail ---\n{tail or last_log[-2000:]}"
            )
    pdf_path = workdir / f"{base}.pdf"
    if not pdf_path.is_file():
        raise PdfBuildError(
            f"{engine} reported success but {pdf_path} was not produced.\n"
            f"--- last engine output ---\n{last_log[-2000:]}"
        )
    if not keep_aux:
        for ext in (".aux", ".log", ".out", ".toc", ".lof", ".lot", ".fls",
                    ".fdb_latexmk", ".synctex.gz"):
            (workdir / f"{base}{ext}").unlink(missing_ok=True)
    return pdf_path


