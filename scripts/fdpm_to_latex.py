def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="fdpm_to_latex.py",
        description=(
            "Render an FDPM academic-paper JSON instance into a self-contained "
            "LaTeX document. Mechanical transcription only — no inferred content."
        ),
    )
    parser.add_argument("input", type=Path, help="Path to the FDPM JSON instance.")
    parser.add_argument(
        "-o", "--output", type=Path, default=None,
        help="Output .tex path (default: <input-basename>.tex).",
    )
    parser.add_argument(
        "--engine", choices=("lualatex", "xelatex", "pdflatex"), default="lualatex",
        help="Target TeX engine; affects preamble (default: lualatex).",
    )
    parser.add_argument(
        "--no-appendix", action="store_true",
        help="Skip the back-matter (methods, theories, glossary, theorists, limitations).",
    )
    parser.add_argument(
        "--toc", action="store_true",
        help="Emit a table of contents after the abstract.",
    )
    parser.add_argument(
        "--bib", type=Path, default=None,
        help="Also write a BibTeX file with the cited works.",
    )
    parser.add_argument(
        "--pdf", action="store_true",
        help=(
            "After writing the .tex, compile it to PDF with the chosen "
            "engine. Runs the engine twice to resolve cross-references. "
            "Auxiliary files are removed unless --keep-aux is set."
        ),
    )
    parser.add_argument(
        "--pdf-passes", type=int, default=2,
        help="Number of engine passes when compiling to PDF (default: 2).",
    )
    parser.add_argument(
        "--keep-aux", action="store_true",
        help="When compiling to PDF, retain .aux / .log / .toc auxiliary files.",
    )
    args = parser.parse_args(argv)

    if not args.input.is_file():
        print(f"error: file not found: {args.input}", file=sys.stderr)
        return 1

    try:
        wb = Workbook.load(args.input)
    except json.JSONDecodeError as e:
        print(f"error: invalid JSON in {args.input}: {e}", file=sys.stderr)
        return 1
    except SchemaError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2

    opts = RenderOptions(
        engine=args.engine,
        include_appendix=not args.no_appendix,
        bib_path=args.bib,
        include_toc=args.toc,
    )

    try:
        renderer = LatexRenderer(wb, opts)
        tex = renderer.render()
    except SchemaError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2

    out_path = args.output or args.input.with_suffix(".tex")
    out_path.write_text(tex, encoding="utf-8")

    # Build report on stderr.
    paper_qid = wb.paper_qid()
    paper_title = ""
    if paper_qid:
        paper_title = (wb.primitives[paper_qid].get("field_values") or {}).get("title", "")
    print(f"[ok] wrote {out_path}", file=sys.stderr)
    print(f"     paper: {paper_title}", file=sys.stderr)
    counts = renderer.tally
    print(
        f"     rendered: "
        f"{counts.get('sections', 0)} sections, "
        f"{counts.get('definitions', 0)} definitions, "
        f"{counts.get('equations', 0)} equations, "
        f"{counts.get('claims', 0)} claims, "
        f"{counts.get('findings', 0)} findings, "
        f"{counts.get('tables', 0)} tables, "
        f"{counts.get('methods', 0)} methods, "
        f"{counts.get('theories', 0)} theories, "
        f"{counts.get('concepts', 0)} concepts, "
        f"{counts.get('theorists', 0)} theorists, "
        f"{counts.get('limitations', 0)} limitations, "
        f"{counts.get('references', 0)} references.",
        file=sys.stderr,
    )
    if opts.bib_path is not None:
        print(f"[ok] wrote {opts.bib_path}", file=sys.stderr)

    if args.pdf:
        try:
            pdf_path = compile_pdf(
                out_path,
                engine=args.engine,
                bib_path=opts.bib_path,
                passes=args.pdf_passes,
                keep_aux=args.keep_aux,
            )
        except PdfBuildError as e:
            print(f"error: PDF build failed:\n{e}", file=sys.stderr)
            return 4
        print(f"[ok] wrote {pdf_path}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
